use std::env;
use std::path::{Path, PathBuf};

use chrono::{DateTime, NaiveDateTime, Utc};
use sqlx::SqlitePool;
use tokio_cron_scheduler::{Job, JobScheduler};

type BoxError = Box<dyn std::error::Error + Send + Sync>;

const DEFAULT_BACKUP_DIR: &str = "./backups";
const DEFAULT_MAX_FILES: usize = 3;
const BACKUP_INTERVAL_HOURS: i64 = 6;
// Keep the cron step in sync with `BACKUP_INTERVAL_HOURS`.
const BACKUP_CRON: &str = "0 0 */6 * * *";
const BACKUP_PREFIX: &str = "keydungeon-";
const BACKUP_SUFFIX: &str = ".db";
const BACKUP_TIMESTAMP_FORMAT: &str = "%Y%m%d-%H%M%S";

#[derive(Clone, Debug)]
struct BackupConfig {
    dir: PathBuf,
    max_files: usize,
    run_on_start: bool,
}

impl BackupConfig {
    fn from_env() -> Self {
        let dir = env::var("BACKUP_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|_| PathBuf::from(DEFAULT_BACKUP_DIR));
        let max_files = env::var("BACKUP_MAX_FILES")
            .ok()
            .and_then(|value| value.parse::<usize>().ok())
            .filter(|value| *value > 0)
            .unwrap_or(DEFAULT_MAX_FILES);

        Self {
            dir,
            max_files,
            run_on_start: env_flag("BACKUP_ON_START", true),
        }
    }
}

/// Starts the in-process database backup scheduler.
///
/// A backup is created every six hours using SQLite's `VACUUM INTO`, which
/// produces a consistent single-file snapshot while the API is running.
pub async fn start(pool: SqlitePool) -> Result<JobScheduler, BoxError> {
    let config = BackupConfig::from_env();

    if let Err(error) = tokio::fs::create_dir_all(&config.dir).await {
        tracing::warn!(
            %error,
            backup_dir = %config.dir.display(),
            "could not create database backup directory"
        );
    }

    let scheduler = JobScheduler::new().await?;
    let job_config = config.clone();
    let job = Job::new_async(BACKUP_CRON, move |_job_id, _scheduler| {
        let pool = pool.clone();
        let config = job_config.clone();

        Box::pin(async move {
            match backup_once(&pool, &config.dir, config.max_files).await {
                Ok(path) => {
                    tracing::info!(path = %path.display(), "database backup created");
                }
                Err(error) => {
                    tracing::error!(%error, "database backup failed");
                }
            }
        })
    })?;

    scheduler.add(job).await?;
    scheduler.start().await?;

    tracing::info!(
        backup_dir = %config.dir.display(),
        max_files = config.max_files,
        cron = BACKUP_CRON,
        "database backup scheduler started"
    );

    Ok(scheduler)
}

/// Creates a startup backup when there is no recent one.
///
/// This catches up after downtime without churning the retained backups on
/// frequent restarts: a snapshot is only taken when no backup exists or the
/// newest one is older than the backup interval.
pub async fn backup_if_due(pool: &SqlitePool) -> Result<Option<PathBuf>, BoxError> {
    let config = BackupConfig::from_env();

    if !config.run_on_start {
        tracing::info!("startup database backup disabled");
        return Ok(None);
    }

    backup_if_due_with(pool, &config, Utc::now()).await
}

async fn backup_if_due_with(
    pool: &SqlitePool,
    config: &BackupConfig,
    now: DateTime<Utc>,
) -> Result<Option<PathBuf>, BoxError> {
    tokio::fs::create_dir_all(&config.dir).await?;

    if let Some((path, created_at)) = newest_backup(&config.dir).await? {
        let age = now.signed_duration_since(created_at);
        if age < chrono::Duration::hours(BACKUP_INTERVAL_HOURS) {
            tracing::info!(
                path = %path.display(),
                age_hours = age.num_hours(),
                "skipping startup database backup, a recent backup already exists"
            );
            return Ok(None);
        }
    }

    let path = backup_once(pool, &config.dir, config.max_files).await?;
    tracing::info!(path = %path.display(), "startup database backup created");

    Ok(Some(path))
}

async fn backup_once(
    pool: &SqlitePool,
    backup_dir: &Path,
    max_files: usize,
) -> Result<PathBuf, BoxError> {
    tokio::fs::create_dir_all(backup_dir).await?;

    let timestamp = Utc::now().format(BACKUP_TIMESTAMP_FORMAT);
    let file_name = format!("{BACKUP_PREFIX}{timestamp}{BACKUP_SUFFIX}");
    let final_path = backup_dir.join(file_name);
    let temp_path = backup_dir.join(format!(
        "{}.tmp",
        final_path
            .file_name()
            .expect("backup path always has a file name")
            .to_string_lossy()
    ));

    // `VACUUM INTO` creates a consistent copy without copying the live WAL and
    // SHM files. The path is generated by this process, not user input.
    let statement = format!(
        "VACUUM INTO '{}'",
        temp_path.to_string_lossy().replace('\'', "''")
    );

    if let Err(error) = sqlx::query(sqlx::AssertSqlSafe(statement))
        .execute(pool)
        .await
    {
        let _ = tokio::fs::remove_file(&temp_path).await;
        return Err(Box::new(error));
    }

    if let Err(error) = tokio::fs::rename(&temp_path, &final_path).await {
        let _ = tokio::fs::remove_file(&temp_path).await;
        return Err(Box::new(error));
    }

    prune_backups(backup_dir, max_files.max(1)).await?;

    Ok(final_path)
}

/// Returns the newest backup and the timestamp encoded in its file name.
async fn newest_backup(backup_dir: &Path) -> Result<Option<(PathBuf, DateTime<Utc>)>, BoxError> {
    let mut newest: Option<(PathBuf, DateTime<Utc>)> = None;

    for path in list_backups(backup_dir).await? {
        let Some(created_at) = backup_timestamp(&path).await else {
            continue;
        };

        if newest
            .as_ref()
            .is_none_or(|(_, current)| created_at > *current)
        {
            newest = Some((path, created_at));
        }
    }

    Ok(newest)
}

async fn backup_timestamp(path: &Path) -> Option<DateTime<Utc>> {
    let name = path.file_name()?.to_string_lossy();
    let stamp = name
        .strip_prefix(BACKUP_PREFIX)?
        .strip_suffix(BACKUP_SUFFIX)?;

    if let Ok(naive) = NaiveDateTime::parse_from_str(stamp, BACKUP_TIMESTAMP_FORMAT) {
        return Some(naive.and_utc());
    }

    // Fall back to the filesystem timestamp if the name is not in our format.
    let modified = tokio::fs::metadata(path).await.ok()?.modified().ok()?;
    Some(DateTime::<Utc>::from(modified))
}

async fn list_backups(backup_dir: &Path) -> Result<Vec<PathBuf>, BoxError> {
    let mut backups = Vec::new();
    let mut entries = tokio::fs::read_dir(backup_dir).await?;

    while let Some(entry) = entries.next_entry().await? {
        if !entry.file_type().await?.is_file() {
            continue;
        }

        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with(BACKUP_PREFIX) && name.ends_with(BACKUP_SUFFIX) {
            backups.push(entry.path());
        }
    }

    Ok(backups)
}

async fn prune_backups(backup_dir: &Path, max_files: usize) -> Result<(), BoxError> {
    let mut backups = list_backups(backup_dir).await?;
    backups.sort();
    let remove_count = backups.len().saturating_sub(max_files);

    for path in backups.into_iter().take(remove_count) {
        if let Err(error) = tokio::fs::remove_file(&path).await {
            tracing::warn!(
                path = %path.display(),
                %error,
                "could not remove old database backup"
            );
        }
    }

    Ok(())
}

fn env_flag(name: &str, default: bool) -> bool {
    match env::var(name) {
        Ok(value) => match value.trim().to_ascii_lowercase().as_str() {
            "1" | "true" | "yes" | "on" => true,
            "0" | "false" | "no" | "off" => false,
            _ => {
                tracing::warn!(
                    variable = name,
                    value = %value,
                    "unrecognised boolean value, using default"
                );
                default
            }
        },
        Err(_) => default,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::TimeZone;
    use sqlx::sqlite::{SqliteConnectOptions, SqlitePoolOptions};
    use std::time::{SystemTime, UNIX_EPOCH};

    struct TestEnv {
        root: PathBuf,
        backup_dir: PathBuf,
        pool: SqlitePool,
    }

    impl TestEnv {
        async fn new(label: &str) -> Self {
            let unique = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos();
            let root = std::env::temp_dir().join(format!(
                "keydungeon-backup-test-{label}-{}-{unique}",
                std::process::id()
            ));
            let data_dir = root.join("data");
            let backup_dir = root.join("backups");
            tokio::fs::create_dir_all(&data_dir).await.unwrap();
            tokio::fs::create_dir_all(&backup_dir).await.unwrap();

            let options = SqliteConnectOptions::new()
                .filename(data_dir.join("keydungeon.db"))
                .create_if_missing(true);
            let pool = SqlitePoolOptions::new()
                .max_connections(1)
                .connect_with(options)
                .await
                .unwrap();

            sqlx::query("CREATE TABLE test (value TEXT NOT NULL)")
                .execute(&pool)
                .await
                .unwrap();
            sqlx::query("INSERT INTO test (value) VALUES ('backup me')")
                .execute(&pool)
                .await
                .unwrap();

            Self {
                root,
                backup_dir,
                pool,
            }
        }

        fn config(&self) -> BackupConfig {
            BackupConfig {
                dir: self.backup_dir.clone(),
                max_files: 3,
                run_on_start: true,
            }
        }

        async fn write_backup(&self, timestamp: DateTime<Utc>) {
            let name = format!(
                "{BACKUP_PREFIX}{}{BACKUP_SUFFIX}",
                timestamp.format(BACKUP_TIMESTAMP_FORMAT)
            );
            tokio::fs::write(self.backup_dir.join(name), b"placeholder")
                .await
                .unwrap();
        }

        async fn backup_count(&self) -> usize {
            list_backups(&self.backup_dir).await.unwrap().len()
        }

        async fn cleanup(self) {
            self.pool.close().await;
            tokio::fs::remove_dir_all(&self.root).await.unwrap();
        }
    }

    #[tokio::test]
    async fn backup_once_creates_consistent_copy_and_prunes_old_files() {
        let env = TestEnv::new("once").await;

        for index in 0..3 {
            let old = Utc.with_ymd_and_hms(2020, 1, 1, 0, 0, index).unwrap();
            env.write_backup(old).await;
        }

        let backup_path = backup_once(&env.pool, &env.backup_dir, 3).await.unwrap();
        assert!(backup_path.exists());

        let backup_options = SqliteConnectOptions::new().filename(&backup_path);
        let backup_pool = SqlitePoolOptions::new()
            .max_connections(1)
            .connect_with(backup_options)
            .await
            .unwrap();
        let value: String = sqlx::query_scalar("SELECT value FROM test")
            .fetch_one(&backup_pool)
            .await
            .unwrap();
        assert_eq!(value, "backup me");
        assert_eq!(env.backup_count().await, 3);

        backup_pool.close().await;
        env.cleanup().await;
    }

    #[tokio::test]
    async fn backup_if_due_creates_when_none_exist() {
        let env = TestEnv::new("due-empty").await;

        let result = backup_if_due_with(&env.pool, &env.config(), Utc::now())
            .await
            .unwrap();

        assert!(result.is_some());
        assert_eq!(env.backup_count().await, 1);
        env.cleanup().await;
    }

    #[tokio::test]
    async fn backup_if_due_skips_recent_backup() {
        let env = TestEnv::new("due-recent").await;
        let now = Utc::now();
        env.write_backup(now - chrono::Duration::hours(1)).await;

        let result = backup_if_due_with(&env.pool, &env.config(), now)
            .await
            .unwrap();

        assert!(result.is_none());
        assert_eq!(env.backup_count().await, 1);
        env.cleanup().await;
    }

    #[tokio::test]
    async fn backup_if_due_creates_when_stale() {
        let env = TestEnv::new("due-stale").await;
        let now = Utc::now();
        env.write_backup(now - chrono::Duration::hours(BACKUP_INTERVAL_HOURS + 1))
            .await;

        let result = backup_if_due_with(&env.pool, &env.config(), now)
            .await
            .unwrap();

        assert!(result.is_some());
        assert_eq!(env.backup_count().await, 2);
        env.cleanup().await;
    }
}
