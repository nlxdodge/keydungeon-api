use argon2::{Algorithm, Argon2, Params, Version};
use password_hash::phc::PasswordHash;
use password_hash::{PasswordHasher, PasswordVerifier};
use zeroize::Zeroizing;

const DEFAULT_PEPPER: &str = "change-me-to-a-long-random-pepper";

#[derive(Debug)]
pub enum PasswordError {
    Hashing,
    Verification,
    BlockingTask,
}

impl std::fmt::Display for PasswordError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            PasswordError::Hashing => write!(f, "Failed to hash password"),
            PasswordError::Verification => write!(f, "Password verification failed"),
            PasswordError::BlockingTask => write!(f, "Password hashing task failed"),
        }
    }
}

impl std::error::Error for PasswordError {}

/// Load the Argon2 pepper from the environment.
///
/// The pepper is a server-side secret that is mixed into every password hash.
/// It is not stored in the database, so a stolen database alone is not enough
/// to start an offline cracking attempt against the hashes.
pub fn pepper() -> Zeroizing<Vec<u8>> {
    let pepper = std::env::var("PASSWORD_PEPPER").unwrap_or_else(|_| DEFAULT_PEPPER.to_string());

    Zeroizing::new(pepper.into_bytes())
}

fn build_argon2(pepper: &[u8]) -> Result<Argon2<'_>, PasswordError> {
    Argon2::new_with_secret(
        pepper,
        Algorithm::default(),
        Version::default(),
        Params::default(),
    )
    .map_err(|_| PasswordError::Hashing)
}

/// Hash a password with Argon2id using the supplied pepper.
///
/// A random salt is generated by `hash_password` and stored inside the PHC
/// string that is returned.
pub fn hash_with_pepper(password: &str, pepper: &[u8]) -> Result<String, PasswordError> {
    let argon2 = build_argon2(pepper)?;

    argon2
        .hash_password(password.as_bytes())
        .map(|hash| hash.to_string())
        .map_err(|_| PasswordError::Hashing)
}

/// Verify a password against an Argon2 PHC hash using the supplied pepper.
///
/// A wrong password is `Ok(false)`. A malformed hash or a hashing failure is
/// reported as an error so callers can distinguish bad credentials from a
/// server-side problem.
pub fn verify_with_pepper(
    password: &str,
    hash: &str,
    pepper: &[u8],
) -> Result<bool, PasswordError> {
    let argon2 = build_argon2(pepper).map_err(|_| PasswordError::Verification)?;
    let parsed_hash = PasswordHash::new(hash).map_err(|_| PasswordError::Verification)?;

    match argon2.verify_password(password.as_bytes(), &parsed_hash) {
        Ok(()) => Ok(true),
        Err(password_hash::Error::PasswordInvalid) => Ok(false),
        Err(_) => Err(PasswordError::Verification),
    }
}

/// Hash a password on the blocking thread pool so Argon2 does not stall the
/// async runtime.
pub async fn hash_async(password: String) -> Result<String, PasswordError> {
    let password = Zeroizing::new(password);

    tokio::task::spawn_blocking(move || {
        let pepper = pepper();
        hash_with_pepper(password.as_str(), pepper.as_slice())
    })
    .await
    .map_err(|_| PasswordError::BlockingTask)?
}

/// Verify a password on the blocking thread pool.
pub async fn verify_async(password: String, hash: String) -> Result<bool, PasswordError> {
    let password = Zeroizing::new(password);

    tokio::task::spawn_blocking(move || {
        let pepper = pepper();
        verify_with_pepper(password.as_str(), &hash, pepper.as_slice())
    })
    .await
    .map_err(|_| PasswordError::BlockingTask)?
}

#[cfg(test)]
mod tests {
    use super::{hash_with_pepper, verify_with_pepper};

    const TEST_PEPPER: &[u8] = b"test-pepper";

    #[test]
    fn hashes_and_verifies_a_password() {
        let hash = hash_with_pepper("correct horse battery staple", TEST_PEPPER)
            .expect("password should hash");

        assert!(hash.starts_with("$argon2"));
        assert!(verify_with_pepper("correct horse battery staple", &hash, TEST_PEPPER).unwrap());
        assert!(!verify_with_pepper("wrong password", &hash, TEST_PEPPER).unwrap());
    }

    #[test]
    fn rejects_a_different_pepper() {
        let hash = hash_with_pepper("correct horse battery staple", TEST_PEPPER)
            .expect("password should hash");

        assert!(
            !verify_with_pepper("correct horse battery staple", &hash, b"other-pepper").unwrap()
        );
    }
}
